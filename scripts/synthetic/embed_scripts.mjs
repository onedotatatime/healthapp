#!/usr/bin/env node
// Writes supabase/functions/_shared/simulate_scripts.ts: the three synthetic scripts as strings, so the edge function
// (which can only ship files under supabase/functions/) can upload them to the boxd machine. MIN-4674.
// Re-run after any change to generate.py, match.py or build_run.py; the Deno test fails until you do.
//   node scripts/synthetic/embed_scripts.mjs
import { readFileSync, writeFileSync } from "node:fs";
import { createHash } from "node:crypto";

const here = new URL(".", import.meta.url);
const out = new URL("../../supabase/functions/_shared/simulate_scripts.ts", here);
const names = ["generate.py", "match.py", "build_run.py"];
const files = Object.fromEntries(names.map((n) => [n, readFileSync(new URL(n, here), "utf8")]));
const sha = (s) => createHash("sha256").update(s, "utf8").digest("hex");

const body = names.map((n) => `  ${JSON.stringify(n)}: ${JSON.stringify(files[n])},`).join("\n");
writeFileSync(
  out,
  `// GENERATED by scripts/synthetic/embed_scripts.mjs from scripts/synthetic/*.py (MIN-4674). Do not edit by hand.
// Synthetic only: these three scripts make the 5,000 invented patients on the boxd machine. A Deno test proves each
// string is byte-for-byte the file in scripts/synthetic/ and the one the recorded run (data/synthetic/run-5000.json) used.
export const SIMULATE_SCRIPTS: Record<string, string> = {
${body}
};
`,
);
console.log(names.map((n) => `${sha(files[n])}  ${n}`).join("\n"));
