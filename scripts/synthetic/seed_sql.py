"""Write the SQL seeds for the matching RPC from the committed synthetic files (MIN-4505, DB part).

  python3 seed_sql.py write  <data_dir> <sql_dir>   writes 006_seed_match_cohort.sql and 007_seed_match_persona.sql
  python3 seed_sql.py parity <data_dir> <schema>    prints one SELECT that compares the SQL lab coding with match.py

Synthetic data only. The cohort codes come from match.features (one definition for Python and the seed);
the lab thresholds come from match.LAB_DEFS. Same input, same bytes: no clock, no randomness.
"""
import json, os, sys
from match import LAB_DEFS, LABEL, features, latest_labs

# match.py marker -> results.analyte_key, using the keys of the extraction's synonym map (MIN-4475,
# _shared/extract.ts KEYS). ana, hla_b27, hba1c, ace, ceruloplasmin and ck have no extraction key yet.
ANALYTE_KEY = {
    "CRP": "crp", "ESR": "esr", "RF": "rf", "anti_CCP": "anti_ccp", "ANA": "ana", "HLA_B27": "hla_b27",
    "TSH": "tsh", "HbA1c": "hba1c", "LDL": "ldl", "Ferritin": "ferritin", "Hemoglobin": "hemoglobin",
    "WBC": "wbc", "VitD": "vitamin_d", "Creatinine": "creatinine", "UricAcid": "uric_acid", "ALT": "alt",
    "ACE": "ace", "Ceruloplasmin": "ceruloplasmin", "CK": "ck",
}
PRINTED = {  # how the persona's seeded lab sheet prints each marker
    "CRP": "C-reactive protein (CRP)", "ESR": "Erythrocyte sedimentation rate (ESR)", "RF": "Rheumatoid factor (RF)",
    "anti_CCP": "Anti-CCP", "Hemoglobin": "Haemoglobin", "UricAcid": "Uric acid", "ALT": "ALT", "ACE": "ACE",
}
# The persona's symptoms and specialty are seeded as the words a letter would use; 005 codes them back.
SYMPTOM_WORDS = {"joint_pain": "joint pain", "morning_stiffness": "morning stiffness"}
SPECIALTY_WORDS = {"spec_rheumatology": "Rheumatology"}
SEED_ISSUER = "Seeded synthetic record (MIN-4505)"
assert set(ANALYTE_KEY) == set(LAB_DEFS)


def q(s):
    return "'" + str(s).replace("'", "''") + "'"


def arr(items):
    return q("{" + ",".join(items) + "}") + "::text[]"


def num(x):
    return repr(float(x)) if isinstance(x, float) else str(x)


def cohort_sql(cohort):
    rows = sorted(cohort, key=lambda r: r["id"])
    for r in rows:
        assert r["synthetic"] is True and r["label"] == LABEL
    lab = ",\n".join(
        "  (%s, %s, %s, %s, %s, %s)" % (q(ANALYTE_KEY[m]), q(u), num(lo), num(hi),
                                        q(a) if a else "null", q(b) if b else "null")
        for m, (u, lo, hi, a, b) in sorted(LAB_DEFS.items(), key=lambda kv: ANALYTE_KEY[kv[0]]))
    co = ",\n".join(  # the first row carries the types; VALUES resolves the rest to them
        "  (%s,%s,%s,%s,%s)" % (q(r["id"]), q(r["country"]), q(r["age_band"]),
                                "true" if r["matching_opt_in"] else "false",
                                arr(sorted(features(r))) if i == 0 else q("{" + ",".join(sorted(features(r))) + "}"))
        for i, r in enumerate(rows))
    keys = ",".join(q(k) for k in sorted(ANALYTE_KEY.values()))
    return f"""-- GENERATED by scripts/synthetic/seed_sql.py from data/synthetic/cohort.json and match.py. Do not edit.
-- Per env. Rendered by `scripts/hdb render <env> 006_seed_match_cohort.sql`. Needs 005_matches.sql.
-- {len(rows)} seeded synthetic cohort rows (label "{LABEL}"): country, age band, opt-in, coded features.
-- No name, no id of a person, no date, nothing below country. Idempotent: loading it twice leaves one copy.

-- Lab thresholds, from match.LAB_DEFS (marker -> analyte_key of the extraction).
insert into __SCHEMA__.match_lab_defs (analyte_key, unit, ref_low, ref_high, code_above, code_below) values
{lab}
on conflict (analyte_key) do update set unit = excluded.unit, ref_low = excluded.ref_low, ref_high = excluded.ref_high,
  code_above = excluded.code_above, code_below = excluded.code_below;
delete from __SCHEMA__.match_lab_defs where analyte_key <> all (array[{keys}]);

-- One statement: upsert every row of the file, then delete any row the file no longer holds.
with src (id, country, age_band, matching_opt_in, codes) as (values
{co}
), up as (
  insert into __SCHEMA__.match_cohort (id, country, age_band, matching_opt_in, codes)
  select * from src
  on conflict (id) do update set country = excluded.country, age_band = excluded.age_band,
    matching_opt_in = excluded.matching_opt_in, codes = excluded.codes
  returning id
)
delete from __SCHEMA__.match_cohort c where not exists (select 1 from src where src.id = c.id);

do $$
begin
  if (select count(*) from __SCHEMA__.match_cohort) <> {len(rows)} then
    raise exception 'match_cohort must hold exactly {len(rows)} rows';
  end if;
end $$;

insert into __SCHEMA__._applied (file) values ('006_seed_match_cohort.sql') on conflict (file) do nothing;
"""


def persona_sql(p):
    """Maria's synthetic record, written into the synthetic patient persona's account (patient.<env>)."""
    assert p["synthetic"] is True and p["imaging"] == []
    by_date = {}
    for lab in p["labs"]:
        by_date.setdefault(lab["date"], []).append(lab)
    docs, results = [], []
    for date in sorted(by_date):
        dkey = "lab-" + date
        docs.append((dkey, "blood_test", date + "-15"))
        for i, lab in enumerate(sorted(by_date[date], key=lambda x: x["marker"])):
            m, v, lo, hi = lab["marker"], lab["value"], lab["ref_low"], lab["ref_high"]
            flag = "high" if v > hi else "low" if v < lo else "normal"
            results.append((dkey, i, PRINTED[m], ANALYTE_KEY[m], v, lab["unit"], lo, hi, flag))
    words = " and ".join(SYMPTOM_WORDS[s] for s in sorted(p["symptoms"]))
    letter_date = max(by_date) + "-20"
    docs.append(("letter", "doctor_letter", letter_date))
    (spec,) = p["specialties"]
    text = words[0].upper() + words[1:] + " in both hands."
    uid = lambda key: "md5('min-4505:persona:%s')::uuid" % key  # fixed ids, so a second load changes nothing
    doc_rows = ",\n".join("    (%s, %s, %s::date)" % (uid(k), q(kind), q(d)) for k, kind, d in docs)
    res_rows = ",\n".join("    (%s, %s, %s, %s, %s, %s, %s, %s, %s)" % (
        uid("%s:%d" % (k, i)), uid(k), q(a), q(key), num(v), q(u), num(lo), num(hi), q(f))
        for k, i, a, key, v, u, lo, hi, f in results)
    return f"""-- GENERATED by scripts/synthetic/seed_sql.py from data/synthetic/persona-maria.json. Do not edit.
-- Per env, dev only for now. Rendered by `scripts/hdb render dev 007_seed_match_persona.sql`. Needs 003 and 005.
-- The synthetic persona's record for the possible-matches demo: {len(docs) - 1} lab sheets and one letter, confirmed,
-- issuer "{SEED_ISSUER}", no file in storage. Synthetic only. Idempotent (fixed ids).
-- The persona stays opted OUT: she turns matching on through healthapp_set_matches_opt_in (F1).
with me as (
  select p.id from __SCHEMA__.profiles p join auth.users u on u.id = p.id
  where u.email = 'patient.__ENV__@healthapp.invalid' and u.raw_app_meta_data ->> 'app' = 'healthapp'
    and u.raw_app_meta_data ->> 'env' = '__ENV__' and p.role = 'patient'
), d (id, kind, exam_date) as (values
{doc_rows}
)
insert into __SCHEMA__.documents (id, patient_id, kind, language, exam_date, issuer, printed_name, printed_id,
                                  identity_status, status, confirmed_at)
select d.id, me.id, d.kind, 'en', d.exam_date, {q(SEED_ISSUER)}, 'PAPADOPOULOU MARIA', 'AK123456', 'match',
       'confirmed', now()
from d cross join me
on conflict (id) do nothing;

with r (id, document_id, analyte, analyte_key, value_num, unit, ref_low, ref_high, flag) as (values
{res_rows}
)
insert into __SCHEMA__.results (id, document_id, patient_id, analyte, analyte_key, value_num, unit, ref_low, ref_high,
                                flag, confidence)
select r.id, r.document_id, d.patient_id, r.analyte, r.analyte_key, r.value_num, r.unit, r.ref_low, r.ref_high,
       r.flag, 1
from r join __SCHEMA__.documents d on d.id = r.document_id
on conflict (id) do nothing;

insert into __SCHEMA__.findings (id, document_id, patient_id, kind, text_original, text_lang, finding_date,
                                 specialty, confidence)
select {uid("letter:0")}, d.id, d.patient_id, 'note', {q(text)}, 'en', {q(letter_date)}::date,
       {q(SPECIALTY_WORDS[spec])}, 1
from __SCHEMA__.documents d where d.id = {uid("letter")}
on conflict (id) do nothing;

do $$
begin
  if (select count(*) from __SCHEMA__.documents where issuer = {q(SEED_ISSUER)}) <> {len(docs)} then
    raise exception 'persona record not seeded: is 003 applied and patient.__ENV__ created?';
  end if;
end $$;

insert into __SCHEMA__._applied (file) values ('007_seed_match_persona.sql') on conflict (file) do nothing;
"""


def parity_sql(cohort, schema):
    """One SELECT: the SQL lab coding must equal match.py's on every threshold edge of every analyte
    (just under, on and just over ref_low and ref_high) and on the cohort's own latest values."""
    vals = {}
    for m, (_u, lo, hi, _a, _b) in LAB_DEFS.items():
        vals[m] = {lo - 0.01, lo, lo + 0.01, hi - 0.01, hi, hi + 0.01, 0, hi * 10 + 1}
    for r in cohort:
        for m, lab in latest_labs(r).items():
            if len(vals[m]) < 24:
                vals[m].add(lab["value"])
    rows = []
    for m in sorted(vals):
        _u, lo, hi, a, b = LAB_DEFS[m]
        for v in sorted(vals[m]):
            v = round(v, 4)
            want = [c for c, hit in ((a, a and v > hi), (b, b and v < lo)) if hit]
            rows.append("(%s,%s,%s)" % (q(ANALYTE_KEY[m]), num(v), arr(want)))
    return f"""select count(*) as lab_values,
       count(*) filter (where got is distinct from want) as mismatches,
       count(*) filter (where cardinality(want) > 0) as coded_values
from (select v.want, {schema}.match_lab_codes(v.analyte_key, v.value_num::numeric) as got
      from (values {",".join(rows)}) as v (analyte_key, value_num, want)) t;"""


if __name__ == "__main__":
    mode, data = sys.argv[1], sys.argv[2]
    cohort = json.load(open(os.path.join(data, "cohort.json")))["records"]
    if mode == "write":
        out = sys.argv[3]
        persona = json.load(open(os.path.join(data, "persona-maria.json")))
        for name, text in (("006_seed_match_cohort.sql", cohort_sql(cohort)),
                           ("007_seed_match_persona.sql", persona_sql(persona))):
            with open(os.path.join(out, name), "w") as f:
                f.write(text)
            print("wrote", name, len(text.encode()), "bytes")
    elif mode == "parity":
        print(parity_sql(cohort, sys.argv[3]))
    else:
        sys.exit("usage: seed_sql.py write <data_dir> <sql_dir> | parity <data_dir> <schema>")
