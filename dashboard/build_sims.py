#!/usr/bin/env python3
"""Writes docs/dashboard/drafts/shared/sim-data.js, the numbers of the "Doctor simulations" view (MIN-4600, CTO decision on MIN-4458).

    python3 dashboard/build_sims.py            write the file
    python3 dashboard/build_sims.py --check    exit 1 if the committed file is not what the two sources produce

Reads only data/synthetic/run-5000.json and data/synthetic/simulation.json (series 1). Whitelist, aggregates only: no per-record row,
no matched id, no persona, nothing from cohort.json, no series 2 or 3 (they rest on an assumption and read as a health claim).
The output is loaded by the public dashboard page, so every field below is chosen by name, never copied by loop.
"""
import json
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SRC = os.path.join(ROOT, "data", "synthetic")
OUT = os.path.join(ROOT, "docs", "dashboard", "drafts", "shared", "sim-data.js")
LABEL = "Seeded synthetic data. Not real patients."
HEADER = ("// Generated by dashboard/build_sims.py from data/synthetic/ (MIN-4600). Aggregates of seeded synthetic runs, whitelist only.\n"
          "// Do not edit by hand: python3 dashboard/build_sims.py --check fails on drift.\n")


def build():
    with open(os.path.join(SRC, "run-5000.json")) as f:
        run = json.load(f)
    with open(os.path.join(SRC, "simulation.json")) as f:
        sim = json.load(f)
    if run.get("synthetic") is not True or sim.get("synthetic") is not True:
        sys.exit("build_sims: a source file is not marked synthetic")

    vm, res = run["vm"], run["result"]
    countries = {}
    for rid in res["matched"]:
        c = run["detail"][str(rid)]["country"]      # counted, never emitted with the id
        countries[c] = countries.get(c, 0) + 1
    by_country = [[c, n] for c, n in sorted(countries.items(), key=lambda kv: (-kv[1], kv[0]))]

    s1 = [s for s in sim["series"] if s["id"] == 1]
    if len(s1) != 1 or s1[0]["key"] != "match_rate":
        sys.exit("build_sims: simulation series 1 is not the match rate")
    if len(sim["x"]["values"]) != len(s1[0]["values"]):
        sys.exit("build_sims: x and series 1 differ in length")

    funnel = res["funnel"]
    data = {
        "label": LABEL,
        "run": {
            "machine": vm["machine"], "provider": vm["provider"], "size": vm["size"],
            "started_at": vm["started_at"], "seconds": vm["seconds"], "deleted": bool(vm["deleted"]),
            "phases": [{"id": p["id"], "at": p["at"], "seconds": p["seconds"]} for p in vm["phases"]],
            "seed": run["seed"], "n": run["n"], "k": run["k"], "min_shared": run["min_shared"],
            "funnel": {"opted_in": funnel["opted_in"], "share_min": funnel["share_min"], "exact": funnel["exact"], "shown": funnel["shown"]},
            "match_count": res["match_count"],
            "by_country": by_country,
        },
        "growth": {
            "label": sim["label"], "seed": sim["seed"], "cohort_size": sim["cohort_size"], "k": sim["k"], "min_shared": sim["min_shared"],
            "x_label": sim["x"]["label"], "x_values": sim["x"]["values"],
            "rate_label": s1[0]["label"], "rate_unit": s1[0]["unit"], "rate_values": s1[0]["values"],
        },
    }
    return HEADER + "const SIMS = " + json.dumps(data, separators=(",", ":"), sort_keys=False) + ";\n"


def main():
    text = build()
    if "--check" in sys.argv[1:]:
        try:
            with open(OUT) as f:
                have = f.read()
        except OSError:
            sys.exit("build_sims: %s is missing; run dashboard/build_sims.py" % OUT)
        if have != text:
            sys.exit("build_sims: sim-data.js has drifted from data/synthetic/; run dashboard/build_sims.py")
        print("sim-data.js ok (%d bytes)" % len(text.encode()))
        return
    with open(OUT, "w") as f:
        f.write(text)
    print("wrote %s (%d bytes)" % (os.path.relpath(OUT, ROOT), len(text.encode())))


if __name__ == "__main__":
    main()
