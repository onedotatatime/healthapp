/** `datetime-local` value (local time, minute precision) for a Date. */
export function toLocalInput(d: Date): string {
  const p = (n: number) => String(n).padStart(2, '0');
  return `${d.getFullYear()}-${p(d.getMonth() + 1)}-${p(d.getDate())}T${p(d.getHours())}:${p(d.getMinutes())}`;
}

export function formatWhen(iso: string): string {
  return new Date(iso).toLocaleString('en-GB', { day: 'numeric', month: 'short', hour: '2-digit', minute: '2-digit' });
}

/** The time was edited when the picked minute differs from the default minute. */
export function isTimeEdited(picked: string, defaultValue: string): boolean {
  return picked !== defaultValue;
}
